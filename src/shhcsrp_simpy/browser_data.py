"""Export the bundled scenarios for the static manual dispatch simulator."""
from __future__ import annotations

import argparse
from dataclasses import asdict
import json
from pathlib import Path

from .data import SERVICE_MEANS, load_scenario


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', nargs='?', type=Path,
                        default=Path('docs/report/simulator/scenarios.js'))
    output = parser.parse_args().output
    data = {'baseService': [[float(v) if v < float('inf') else None for v in row]
                            for row in SERVICE_MEANS], 'scenarios': {}}
    for code in 'ABCD':
        scenario = load_scenario(code)
        data['scenarios'][code] = {'name': scenario.name, 'jobs': [asdict(job) for job in scenario.jobs],
                                   'nurses': scenario.nurse_skills, 'preferences': scenario.preferences.tolist(),
                                   'depot': scenario.depot, 'horizon': scenario.horizon,
                                   'speed': scenario.speed, 'maxWait': scenario.max_wait}
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('/* Generated by python -m shhcsrp_simpy.browser_data. */\n'
                      'globalThis.DISPATCH_DATA = '+json.dumps(data, separators=(',', ':'),
                                                                allow_nan=False)+';\n', encoding='utf-8')


if __name__ == '__main__':
    main()
